// Emits GeneratedIdentifierData.cs from acorn's generated identifier data,
// escaping every non-ASCII code unit as \uXXXX so the C# source stays ASCII.
const path = require("path")
const fs = require("fs")

const GEN = path.resolve(__dirname, "../../acorn/src/generated")
const OUT = path.resolve(__dirname, "../src/Acorn/GeneratedIdentifierData.cs")

function loadArray(file) {
  const txt = fs.readFileSync(path.join(GEN, file), "utf8")
  const m = txt.match(/\[([\s\S]*)\]/)
  return m[1].split(",").map(s => s.trim()).filter(s => s.length).map(Number)
}
function loadString(file) {
  // These modules `export default "..."`. Evaluate safely by extracting the literal.
  const txt = fs.readFileSync(path.join(GEN, file), "utf8")
  const m = txt.match(/export default\s+("(?:[^"\\]|\\.)*")/)
  // eslint-disable-next-line no-eval
  return eval(m[1])
}

function csEscape(str) {
  let out = ""
  for (const ch of str) {
    const code = ch.codePointAt(0)
    if (code === 0x22) out += '\\"'
    else if (code === 0x5c) out += "\\\\"
    else if (code >= 0x20 && code < 0x7f) out += ch
    else if (code <= 0xffff) out += "\\u" + code.toString(16).padStart(4, "0")
    else out += "\\U" + code.toString(16).padStart(8, "0")
  }
  return out
}

const astralCodes = loadArray("astralIdentifierCodes.js")
const astralStartCodes = loadArray("astralIdentifierStartCodes.js")
const nonAsciiChars = loadString("nonASCIIidentifierChars.js")
const nonAsciiStartChars = loadString("nonASCIIidentifierStartChars.js")
const scriptValuesAdded = loadString("scriptValuesAddedInUnicode.js")

function fmtArray(arr) {
  const lines = []
  for (let i = 0; i < arr.length; i += 20) {
    lines.push("        " + arr.slice(i, i + 20).join(", ") + ",")
  }
  return lines.join("\n")
}

const cs = `// <auto-generated>
// This file was generated by dotnet/tools/gen-identifier-data.js from acorn's
// generated Unicode identifier data. Do not modify manually.
// </auto-generated>
namespace Acorn;

internal static class GeneratedIdentifierData
{
    // Run-length/offset encoded ranges of >0xffff identifier code points.
    public static readonly int[] AstralIdentifierCodes =
    {
${fmtArray(astralCodes)}
    };

    public static readonly int[] AstralIdentifierStartCodes =
    {
${fmtArray(astralStartCodes)}
    };

    public const string NonASCIIidentifierChars = "${csEscape(nonAsciiChars)}";

    public const string NonASCIIidentifierStartChars = "${csEscape(nonAsciiStartChars)}";

    public const string ScriptValuesAddedInUnicode = "${csEscape(scriptValuesAdded)}";
}
`

fs.writeFileSync(OUT, cs)
console.log(`Wrote ${OUT}`)
console.log(`astralCodes: ${astralCodes.length}, astralStartCodes: ${astralStartCodes.length}`)
console.log(`nonAsciiChars len: ${nonAsciiChars.length}, startChars len: ${nonAsciiStartChars.length}`)
